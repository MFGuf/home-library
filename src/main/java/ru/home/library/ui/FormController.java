package ru.home.library.ui;

/**
 * Общий контракт для контроллеров форм добавления/редактирования.
 * <p>
 * Каждая форма (книга, автор, категория) умеет два действия:
 * <ul>
 *     <li>{@link #validate()} — проверить корректность полей формы,
 *         вернуть текст ошибки или {@code null}, если всё в порядке;</li>
 *     <li>{@link #collect()} — собрать из полей формы объект модели,
 *         который затем сохраняется в базе данных.</li>
 * </ul>
 *
 * @param <T> тип редактируемой сущности
 */
public interface FormController<T> {

    /** @return текст ошибки либо {@code null}, если поля заполнены корректно. */
    String validate();

    /** @return собранную из полей формы сущность. */
    T collect();
}