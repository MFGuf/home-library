package ru.home.library.dao;

import java.util.List;
import java.util.Optional;

/**
 * Базовый интерфейс доступа к данным (паттерн DAO, принцип абстракции).
 * <p>
 * Все DAO-классы реализуют одинаковый набор операций:
 * поиск всех записей, поиск по идентификатору, сохранение (вставка
 * или обновление) и удаление. Благодаря этому сервисный слой может
 * работать с любой сущностью единообразно.
 *
 * @param <T> тип сущности, наследующей {@link ru.home.library.model.Entity}
 */
public interface CrudDao<T> {

    /** Возвращает все записи сущности. */
    List<T> findAll();

    /** Возвращает запись по идентификатору (если она существует). */
    Optional<T> findById(long id);

    /**
     * Сохраняет сущность: вставляет новую запись (если {@code id == 0})
     * либо обновляет существующую. После вставки объекту присваивается id.
     */
    T save(T entity);

    /** Удаляет запись по идентификатору. */
    void delete(long id);
}