package ru.home.library.model;

/**
 * Базовый класс для всех сущностей предметной области.
 * <p>
 * Показывает применение принципа наследования: каждый объект модели
 * (книга, автор, категория, экземпляр) имеет уникальный идентификатор,
 * который присваивается базой данных при сохранении.
 * Значение {@code id <= 0} означает, что запись ещё не была сохранена в БД.
 */
public abstract class Entity {

    /** Уникальный идентификатор записи в базе данных (0 = ещё не сохранена). */
    private long id;

    public long getId() {
        return id;
    }

    public void setId(long id) {
        this.id = id;
    }

    /** @return {@code true}, если объект ещё не сохранён в БД. */
    public boolean isNew() {
        return id <= 0;
    }
}